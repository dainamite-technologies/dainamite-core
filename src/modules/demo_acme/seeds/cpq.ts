export type AcmeCpqSeedResult = {
  offerings: number
  quoteNumbers: string[]
  orderNumber: string | null
  subscriptionId: string | null
  /** Billing account the CPQ → billing connector created for the order. */
  billingAccountId: string | null
}

function isoDay(date: Date): string {
  return date.toISOString().slice(0, 10)
}

// ─── Catalog (master data, written directly — same as the GIX seed) ──────

async function seedCatalog(em: EntityManager, scope: Scope): Promise<Map<string, string>> {
  // Ids are generated by the database, so they are read after each flush.
  const products = new Map<string, CatalogProduct>()
  for (const p of ACME_PRODUCTS) {
    const product = em.create(CatalogProduct, {
      ...scope,
      title: p.title,
      sku: p.sku,
      handle: p.handle,
      productType: 'configurable',
      isConfigurable: true,
      isActive: true,
    } as never)
    em.persist(product)
    products.set(p.sku, product as CatalogProduct)
  }
  await em.flush()
  const productIds = new Map([...products].map(([k, e]) => [k, e.id]))

  const specs = new Map<string, CpqProductSpecification>()
  for (const s of ACME_SPECS) {
    const spec = em.create(CpqProductSpecification, {
      ...scope,
      productId: productIds.get(s.productSku)!,
      code: s.code,
      name: s.name,
      specType: s.specType,
      isAssetizable: s.isAssetizable,
      lifecycleStatus: 'active',
      version: 1,
    } as never)
    em.persist(spec)
    specs.set(s.code, spec as CpqProductSpecification)
  }
  await em.flush()
  const specIds = new Map([...specs].map(([k, e]) => [k, e.id]))

  const productOfSpec = (specCode: string) => productIds.get(ACME_SPECS.find((s) => s.code === specCode)!.productSku)!
  for (const a of ACME_ATTRIBUTES) {
    em.persist(
      em.create(CpqProductAttribute, {
        ...scope,
        productId: productOfSpec(a.specCode),
        specId: specIds.get(a.specCode)!,
        code: a.code,
        name: a.name,
        attributeType: a.attributeType,
        options: a.options,
        sortOrder: 0,
        isRequired: a.isRequired,
        resolutionTime: a.resolutionTime,
      } as never),
    )
  }

  const offerings = new Map<string, CpqProductOffering>()
  for (const o of ACME_OFFERINGS) {
    const offering = em.create(CpqProductOffering, {
      ...scope,
      specId: specIds.get(o.specCode)!,
      code: o.code,
      name: o.name,
      offeringType: o.offeringType,
      designTimeValues: o.designTimeValues,
      lifecycleStatus: 'active',
    } as never)
    em.persist(offering)
    offerings.set(o.code, offering as CpqProductOffering)
  }
  await em.flush()
  const offeringIds = new Map([...offerings].map(([k, e]) => [k, e.id]))

  for (const c of ACME_CHARGES) {
    em.persist(
      em.create(CpqProductCharge, {
        ...scope,
        productId: productIds.get(c.productSku)!,
        offeringId: offeringIds.get(c.offeringCode)!,
        code: c.code,
        name: c.name,
        chargeType: c.chargeType,
        chargeModel: 'flat',
        pricingMethod: 'fixed',
        fixedPrice: c.fixedPrice,
        currencyCode: ACME_CPQ_CURRENCY,
        sortOrder: 0,
      } as never),
    )
  }

  const slots: Array<[(typeof ACME_SLOTS)[number], CpqBundleSlot]> = []
  for (const slotDef of ACME_SLOTS) {
    const slot = em.create(CpqBundleSlot, {
      ...scope,
      specId: specIds.get(slotDef.bundleSpecCode)!,
      targetSpecId: specIds.get(slotDef.targetSpecCode)!,
      componentGroup: slotDef.componentGroup,
      name: slotDef.name,
      cardinalityMin: 1,
      cardinalityMax: 1,
      sortOrder: slotDef.sortOrder,
    } as never)
    em.persist(slot)
    slots.push([slotDef, slot as CpqBundleSlot])
  }
  await em.flush()
  for (const [slotDef, slot] of slots) {
    em.persist(
      em.create(CpqOfferingComponent, {
        ...scope,
        offeringId: offeringIds.get(ACME_BUNDLE_OFFERING)!,
        slotId: slot.id,
        childOfferingId: offeringIds.get(slotDef.defaultOfferingCode)!,
        isDefault: true,
        sortOrder: 0,
      } as never),
    )
  }
  await em.flush()
  return offeringIds
}

// ─── Quote → order → activation ──────────────────────────────────────────

/**
 * Seeds the ACME CPQ catalog, then replays the Brightside Solar sale through
 * the CPQ services: quote (bundle + 600 Mbps + ONT) → accepted → order →
 * billing setup (new account, bills on the 18th) → activated → subscription
 * active, plus a second empty quote.
 *
 * Activation emits `cpq.subscription.activated`, whose connector subscriber is
 * persistent (run by the queue worker, i.e. after `mercato init` returns). The
 * billing replay needs that account now, so the emitted payload is captured
 * and the connector's own handler is run inline. The handler is idempotent
 * (reuses the applied account, items deduplicate on `source_ref`), so when the
 * worker later drains the queued copy it is a no-op.
 */
export async function seedAcmeCpq(
  em: EntityManager,
  container: AwilixContainer,
  scope: Scope,
  customerIds: Map<string, string>,
  options: { now?: Date } = {},
): Promise<AcmeCpqSeedResult> {
  const anchor = options.now ?? new Date()
  const offeringIds = await seedCatalog(em, scope)
  const result: AcmeCpqSeedResult = {
    offerings: offeringIds.size,
    quoteNumbers: [],
    orderNumber: null,
    subscriptionId: null,
    billingAccountId: null,
  }

  const customerId = customerIds.get(ACME_CPQ_CUSTOMER)
  if (!customerId) return result

  const quoting = container.resolve('cpqQuotingService') as DefaultCpqQuotingService
  const orders = container.resolve('cpqOrderService') as DefaultCpqOrderService
  const inventory = container.resolve('cpqInventoryService') as DefaultCpqInventoryService
  const bus = container.resolve('commandBus') as CommandBus

  // Quote 1 — Internet Family Bundle with its two default components.
  let quote = await quoting.createQuote({ customerId, currencyCode: ACME_CPQ_CURRENCY }, scope)
  quote = await quoting.addQuoteItem(
    quote.id,
    { offeringId: offeringIds.get(ACME_BUNDLE_OFFERING)!, configuration: {}, quantity: 1 },
    scope,
  )
  const bundleLineId = quote.lines.find((l) => l.offeringId === offeringIds.get(ACME_BUNDLE_OFFERING))?.lineId
  for (const slot of ACME_SLOTS) {
    quote = await quoting.addQuoteItem(
      quote.id,
      { offeringId: offeringIds.get(slot.defaultOfferingCode)!, configuration: {}, quantity: 1, parentLineId: bundleLineId },
      scope,
    )
  }
  quote = await quoting.recalculate(quote.id, { save: true }, scope)
  for (const status of ['ready', 'with_customer', 'accepted']) {
    if (quote.cpqStatus !== status) quote = await quoting.transitionStatus(quote.id, status, scope)
  }
  result.quoteNumbers.push(quote.quoteNumber)

  const order = await orders.convertQuoteToOrder(quote.id, scope)
  result.orderNumber = order.orderNumber

  // Billing setup on the order, as the operator saved it: a new account
  // named after the customer, billed monthly on the 18th from the 18th.
  const billDate = isoDay(acmeDate(anchor, { day: ACME_CPQ_BILL_DAY }))
  await bus.execute(ORDER_SETUP_SAVE_COMMAND_ID, {
    input: {
      ...scope,
      orderId: order.id,
      body: {
        accountMode: 'new',
        accountOverrides: {
          name: ACME_CPQ_CUSTOMER,
          billCycle: 'monthly',
          billCycleInterval: 1,
          billCycleDay: String(ACME_CPQ_BILL_DAY),
          nextBillDate: billDate,
        },
        defaultBillStartDate: billDate,
      },
    },
    ctx: {
      container,
      auth: null,
      organizationScope: null,
      selectedOrganizationId: scope.organizationId,
      organizationIds: [scope.organizationId],
    },
  } as never)

  let activated: ActivatedPayload | null = null
  const untap = registerGlobalEventTap((event, payload) => {
    const p = payload as ActivatedPayload | undefined
    if (event === 'cpq.subscription.activated' && p?.tenantId === scope.tenantId && p.sourceOrderId === order.id) {
      activated = p
    }
  })
  try {
    await orders.activateOrder(order.id, scope)
  } finally {
    untap()
  }

  const payload = activated as ActivatedPayload | null
  if (payload) {
    await handleSubscriptionActivated(payload)
    await inventory.transitionSubscriptionStatus(payload.subscriptionId, 'active', scope)
    result.subscriptionId = payload.subscriptionId
    const setupService = container.resolve('cpqBillingOrderSetupService') as CpqBillingOrderSetupService
    const setup = await setupService.findSetup(scope, order.id)
    result.billingAccountId = setup?.appliedBillingAccountId ?? null
  }

  // Quote 2 — opened for the same customer and left empty.
  const draft = await quoting.createQuote({ customerId, currencyCode: ACME_CPQ_CURRENCY }, scope)
  result.quoteNumbers.push(draft.quoteNumber)

  return result
}
