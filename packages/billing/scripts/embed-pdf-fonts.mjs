/**
 * Regenerates `src/modules/billing/lib/pdf/fonts/embeddedFonts.ts` from the
 * subset TTFs next to it (Noto Sans Regular / Bold, SIL OFL 1.1 — see
 * OFL.txt). The fonts are embedded as base64 so the PDF renderer works the
 * same from `src`, `dist`, a Next.js server bundle and Jest — no runtime
 * asset path to resolve.
 *
 * Subset used (pyftsubset, fonttools):
 *   --unicodes="U+0020-007E,U+00A0-017F,U+2010-2027,U+2030-203A,U+20AC,U+2122,U+2212"
 *   --layout-features='kern,liga' --no-hinting
 * i.e. Basic Latin, Latin-1, Latin Extended-A (Polish, Czech, …), dashes,
 * quotes, ellipsis, euro sign.
 *
 * Usage: node scripts/embed-pdf-fonts.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const dir = join(root, 'src/modules/billing/lib/pdf/fonts')
const b64 = (name) => readFileSync(join(dir, name)).toString('base64')

const out = `// GENERATED by scripts/embed-pdf-fonts.mjs — do not edit.
// Noto Sans (subset: Latin, Latin-1, Latin Extended-A, punctuation, €).
// Copyright 2022 The Noto Project Authors. SIL Open Font License 1.1 (OFL.txt).

export const NOTO_SANS_REGULAR_BASE64 =
  '${b64('NotoSans-Regular.ttf')}'

export const NOTO_SANS_BOLD_BASE64 =
  '${b64('NotoSans-Bold.ttf')}'
`
writeFileSync(join(dir, 'embeddedFonts.ts'), out)
console.log('embeddedFonts.ts written')
